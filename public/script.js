const express = require("express");
const dotenv = require("dotenv");
const Groq = require("groq-sdk");


// ========================================
// ตั้งค่า ENV
// ========================================

dotenv.config();


// ========================================
// สร้าง Express
// ========================================

const app = express();


// ========================================
// Middleware
// ========================================

app.use(express.json());

app.use(express.static("public"));


// ========================================
// เชื่อมต่อ Groq
// ========================================

const groq = new Groq({

    apiKey: process.env.GROQ_API_KEY

});


// ========================================
// Beauty AI API
// ========================================

app.post("/api/analyze", async (req, res) => {

    try {

        // รับข้อมูลจากเว็บไซต์

        const {
            age,
            skin,
            face,
            style,
            hair
        } = req.body;


        // ========================================
        // Prompt สำหรับ Beauty AI
        // ========================================

        const prompt = `

คุณคือ "Beauty AI"
ผู้ช่วยแนะนำความงามส่วนบุคคล

หน้าที่ของคุณคือวิเคราะห์ข้อมูลของผู้ใช้
และให้คำแนะนำด้านความงามที่เหมาะสม


ข้อมูลของผู้ใช้

- อายุ: ${age} ปี

- สภาพผิว: ${skin}

- รูปหน้า: ${face}

- สไตล์ที่ชอบ: ${style}

- ทรงผมที่ผู้ใช้เลือก: ${hair}


กรุณาวิเคราะห์ข้อมูลทั้งหมด
และให้คำแนะนำในหัวข้อต่อไปนี้


1. 💇‍♀️ ทรงผม

วิเคราะห์ทรงผมที่ผู้ใช้เลือก
ว่ามีความเหมาะสมกับรูปหน้า
และสไตล์ที่ผู้ใช้ชอบอย่างไร

ถ้าทรงผมที่เลือกไม่ค่อยเหมาะ
ให้แนะนำวิธีปรับทรง
แทนการบอกว่าไม่เหมาะอย่างเดียว


2. 💄 การแต่งหน้า

แนะนำสไตล์การแต่งหน้า
ที่เหมาะกับผู้ใช้

เช่น

- รูปแบบการแต่งหน้า
- การเขียนคิ้ว
- การแต่งตา
- การปัดแก้ม
- การทาปาก


3. 🎨 โทนสีเครื่องสำอาง

แนะนำโทนสีที่เหมาะสม

เช่น

- สีชมพู
- สีพีช
- สีนู้ด
- สีแดง
- สีโทนอุ่น
- สีโทนเย็น


4. 💅 เล็บ

แนะนำ

- สีเล็บ
- รูปแบบเล็บ
- ลวดลายเล็บ

ให้เข้ากับสไตล์ของผู้ใช้


5. 👗 การแต่งตัว

แนะนำ

- สไตล์เสื้อผ้า
- สีเสื้อผ้า
- เครื่องประดับ
- รองเท้า

ให้เข้ากับลุคโดยรวม


6. ✨ คำแนะนำเพิ่มเติม

ให้คำแนะนำเพิ่มเติม
เพื่อช่วยให้ผู้ใช้สามารถนำคำแนะนำ
ไปใช้สร้างลุคของตัวเองได้ง่ายขึ้น


ข้อกำหนดสำคัญ

- ตอบเป็นภาษาไทย
- ใช้ภาษาที่เข้าใจง่าย
- แบ่งคำตอบเป็นหัวข้อ
- ใช้ Emoji ได้อย่างเหมาะสม
- ให้คำแนะนำเฉพาะบุคคล
- ห้ามวินิจฉัยโรค
- ห้ามให้คำแนะนำทางการแพทย์
- ไม่ควรกล่าวอ้างว่าผู้ใช้จะต้องมีลักษณะตามคำแนะนำ
- ใช้คำว่า "แนะนำ" หรือ "อาจเหมาะ" แทนการฟันธง


กรุณาสรุปผลให้ดูอ่านง่าย
และเหมาะสำหรับแสดงบนเว็บไซต์ Beauty AI

        `;


        // ========================================
        // ส่งข้อมูลไป Groq
        // ========================================

        const completion =
            await groq.chat.completions.create({

                messages: [

                    {
                        role: "system",

                        content:
                            "คุณคือ Beauty AI ผู้ช่วยด้านความงามที่สุภาพ ให้คำแนะนำที่เข้าใจง่ายและเหมาะกับแต่ละบุคคล"
                    },

                    {
                        role: "user",

                        content: prompt
                    }

                ],


                // โมเดล Groq
                model: "openai/gpt-oss-20b",


                // ความสร้างสรรค์
                temperature: 0.7

            });


        // ========================================
        // รับคำตอบจาก AI
        // ========================================

        const result =
            completion.choices[0].message.content;


        // ========================================
        // ส่งคำตอบกลับเว็บไซต์
        // ========================================

        res.json({

            result: result

        });


    } catch (error) {

        console.error(
            "Groq API Error:",
            error
        );


        res.status(500).json({

            error:
                "ไม่สามารถเชื่อมต่อ Beauty AI ได้ กรุณาตรวจสอบ API Key และการเชื่อมต่อ"

        });

    }

});


// ========================================
// เปิด Server
// ========================================

app.listen(3000, () => {

    console.log(
        "Beauty AI running at http://localhost:3000"
    );

});